#!/usr/bin/env python3
"""Generates tests/semantic/cases/CtorSpill.java.

    python3 tests/semantic/gen_ctorspill.py > tests/semantic/cases/CtorSpill.java

The case needs a constructor that javac accepts (under 64 KB of bytecode) but
whose DEX translation is over 64 KB, with more values live at every cut than a
method descriptor can carry (255 slots, JVMS 4.3.3). Written by hand that is
thousands of `put` calls, so it is generated: deterministic (fixed seed), and
nothing beyond Python 3. NKEYS and NPUTS size it; the defaults give about 37 KB
of javac bytecode and 69-74 KB of translation in all three suite modes.
"""
import random
import sys

NKEYS = int(sys.argv[1]) if len(sys.argv) > 1 else 300
NPUTS = int(sys.argv[2]) if len(sys.argv) > 2 else 2900
NMAPS = 5
PER_LINE = 6
rnd = random.Random(20261025)

HEADER = """\
// dexsem: no-split-force
// Semantic cover for the constructor spill (MethodSplitter, THE <init> SPILL):
// a constructor too big for one JVM method, whose live values do not fit a
// method descriptor, so its parts receive them through fields of the object
// under construction.
//
// GENERATED by tests/semantic/gen_ctorspill.py -- edit that, not this file.
//
// Unlike Split and ClinitTable this case reaches the REAL threshold, so the
// plain suite exercises it: javac accepts Big's constructor (about 37 KB of
// bytecode), but d8 and R8 keep its 300 boxed keys in registers and shuttle
// them into low registers for every call, so the translation is 69-74 KB with
// more than 340 values live at every legal cut. That is the shape of the
// constructor that stopped WhatsApp 2.26.42.71 from starting (X/08W.<init>:
// five ImmutableMaps filled from a shared pool of boxed values). Without the
// spill the constructor is stubbed and every `new Big` throws.
//
// WHAT EACH PART IS FOR.
//   field state   five maps filled from the shared pool, plus long and double
//                 accumulators, compared through order-sensitive digests
//   finals        Big is nested, so its class file is version 55, where only
//                 <init> itself may write a final field -- and Big's finals
//                 are written from the last part
//   nesting       the constructor builds another Big midway (depth > 0); the
//                 inner construction must not disturb the outer one's values
//   escape        `this` is handed to peek() midway and at the end
//   inheritance   Sub's constructor runs Big's through super()
//   a late throw  new Big(-1, ...) throws from the last part, after super()
//   threads       six threads construct concurrently, and each result must
//                 equal a single-threaded construction
//
// `dexsem: no-split-force`: DEX2JVM_SPLIT_FORCE shrinks the part budget far
// below what one spilled part's entry stub needs, and the forced path has no
// stub fallback, so under it Big fails to translate by design and run.sh
// skips this case.
"""

out = []
w = out.append
w(HEADER.rstrip("\n"))
w("import java.util.ArrayList;")
w("import java.util.LinkedHashMap;")
w("import java.util.List;")
w("import java.util.Map;")
w("")
w("public class CtorSpill {")
w("")
w("    static final StringBuffer LOG = new StringBuffer();")
w("")
w("    static class Base {")
w("        final String tag;")
w("        Base(String tag) { this.tag = tag; }")
w("    }")
w("")
w("    /** Seen by the constructor while it runs: `this` escapes mid-way. */")
w("    static void peek(Big b) {")
w("        LOG.append(\"peek:\").append(b.tag).append(':').append(b.m0 == null)")
w("           .append(':').append(b.child == null ? \"-\" : b.child.tag).append(';');")
w("    }")
w("")
w("    static void p(Map<Integer, Object> m, Integer k, Object v) { m.put(k, v); }")
w("")
w("    /** Nested, so the class carries NestHost/NestMembers and is emitted at")
w("     *  class version 55, where only <init> itself may write a final field. */")
w("    static class Big extends Base {")
for i in range(NMAPS):
    w("        final Map<Integer, Object> m%d;" % i)
w("        final long sum;")
w("        final double mean;")
w("        final int count;")
w("        final Big child;")
w("")
w("        Big(int depth, String tag) {")
w("            super(tag);")
for i in range(NMAPS):
    w("            Map<Integer, Object> b%d = new LinkedHashMap<>();" % i)
w("            long acc = depth;")
w("            double dsum = 0.5 * depth;")
# keys: boxed integers computed from depth so nothing folds to a constant
for i in range(NKEYS):
    w("            Integer k%d = Integer.valueOf(depth * 1000 + %d);" % (i, (i * 37) % 997))
NVALS = 40
for i in range(NVALS):
    w("            String v%d = tag + %d;" % (i, i))
w("            Boolean t = Boolean.valueOf(depth >= 0), f = Boolean.valueOf(depth < 0);")
# a nested construction of the same class and an escape of `this`, mid-way
mid = NPUTS // 2
quarter = NPUTS // 4
stmts = []
# make sure every key is used early AND late so all stay live everywhere
for n in range(NPUTS):
    if n < NKEYS:
        k = n
    elif n >= NPUTS - NKEYS:
        k = n - (NPUTS - NKEYS)
    else:
        k = rnd.randrange(NKEYS)
    m = rnd.randrange(NMAPS)
    r = rnd.randrange(NVALS + 2)
    v = "t" if r == NVALS else "f" if r == NVALS + 1 else "v%d" % r
    stmts.append("p(b%d, k%d, %s);" % (m, k, v))
body = []
for n, s in enumerate(stmts):
    if n == quarter:
        body.append("acc += k%d; dsum += k%d / 4.0;" % (1, 2))
    if n == mid:
        body.append("peek(this);")
    if n == mid + 1:
        body.append("Big kid = depth > 0 ? new Big(depth - 1, tag + \"/\" + depth) : null;")
    body.append(s)
line = []
for s in body:
    line.append(s)
    if len(line) == PER_LINE:
        w("            " + " ".join(line))
        line = []
if line:
    w("            " + " ".join(line))
w("            if (depth < 0) throw new IllegalStateException(\"late throw \" + k0 + v1);")
w("            acc += k%d + k%d; dsum += k%d;" % (NKEYS - 1, NKEYS // 2, NKEYS - 2))
for i in range(NMAPS):
    w("            this.m%d = b%d;" % (i, i))
w("            this.child = kid;")
w("            this.sum = acc;")
w("            this.mean = dsum;")
w("            this.count = b0.size() + b1.size() + b2.size() + b3.size() + b4.size();")
w("            peek(this);")
w("        }")
w("")
w("        String state() {")
w("            StringBuilder sb = new StringBuilder(tag).append('|').append(sum).append('|')")
w("                .append(mean).append('|').append(count);")
w("            for (Map<Integer, Object> m : List.of(m0, m1, m2, m3, m4)) {")
w("                sb.append('|').append(m.size()).append('=').append(digest(m));")
w("            }")
w("            if (child != null) sb.append(\" child[\").append(child.state()).append(']');")
w("            return sb.toString();")
w("        }")
w("    }")
w("")
w("    /** A subclass whose constructor runs the rescued one through super(). */")
w("    static final class Sub extends Big {")
w("        final String extra;")
w("        Sub(String tag) { super(1, tag); extra = \"sub:\" + m3.size(); }")
w("    }")
w("")
w("    /** Order-sensitive digest of a map's entries, so every key, value and")
w("     *  insertion position counts without printing thousands of lines. */")
w("    static long digest(Map<Integer, Object> m) {")
w("        long h = 1125899906842597L;")
w("        for (Map.Entry<Integer, Object> e : m.entrySet()) {")
w("            h = 31 * h + e.getKey();")
w("            h = 31 * h + String.valueOf(e.getValue()).hashCode();")
w("        }")
w("        return h;")
w("    }")
w("")
w("    public static void main(String[] a) throws Exception {")
w("        Big one = new Big(2, \"root\");")
w("        System.out.println(\"one: \" + one.state());")
w("        System.out.println(\"log: \" + LOG);")
w("        Sub sub = new Sub(\"sub\");")
w("        System.out.println(\"sub: \" + sub.extra + \" \" + sub.state());")
w("        try {")
w("            new Big(-1, \"bad\");")
w("            System.out.println(\"bad: no throw\");")
w("        } catch (IllegalStateException e) {")
w("            System.out.println(\"bad: \" + e.getMessage());")
w("        }")
w("        // Concurrent constructions must not see each other's values.")
w("        List<Thread> ts = new ArrayList<>();")
w("        String[] got = new String[6];")
w("        for (int i = 0; i < got.length; i++) {")
w("            final int n = i;")
w("            Thread th = new Thread(() -> {")
w("                String s = null;")
w("                for (int r = 0; r < 20; r++) s = new Big(n % 3, \"t\" + n).state();")
w("                got[n] = s;")
w("            });")
w("            ts.add(th);")
w("            th.start();")
w("        }")
w("        for (Thread th : ts) th.join();")
w("        for (int i = 0; i < got.length; i++) {")
w("            System.out.println(\"thread\" + i + \": \" + got[i].equals(new Big(i % 3, \"t\" + i).state())")
w("                + \" \" + got[i].length());")
w("        }")
w("    }")
w("}")
# Bytes, so the file has LF line ends on every platform.
sys.stdout.buffer.write(("\n".join(out) + "\n").encode("utf-8"))
